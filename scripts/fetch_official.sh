#!/usr/bin/env bash
# Download the baseline from the official GKI build the phone runs: its exact
# source manifest, vmlinux.symvers, .config, BTF and the module-signing
# certificate built into its kernel.
# Usage: fetch_official.sh <build id> <out dir>
set -euo pipefail

BID=$1
OUT=$2
HERE=$(cd "$(dirname "$0")/.." && pwd)
URL="https://ci.android.com/builds/submitted/${BID}/kernel_aarch64/latest/raw"
mkdir -p "$OUT"

fetch() {
  curl -fsSL --retry 5 --retry-delay 15 -o "$OUT/$2" "$URL/$1"
  echo "$2: $(stat -c %s "$OUT/$2") bytes"
}
fetch "manifest_${BID}.xml" manifest.xml
fetch vmlinux.symvers vmlinux.symvers
fetch kernel_aarch64_dot_config config
fetch gki-info.txt gki-info.txt
fetch Image Image
cat "$OUT/gki-info.txt"

python3 "$HERE/tools/extract.py" btf "$OUT/Image" "$OUT/vmlinux.btf"

# The build-time key that signed this build's system_dlkm modules.
python3 "$HERE/tools/extract.py" certs "$OUT/Image" "$OUT/certs"
count=$(find "$OUT/certs" -name '*.der' | wc -l)
if [ "$count" != 1 ]; then
  echo "expected exactly one built-in certificate, found $count" >&2
  exit 1
fi
mv "$OUT/certs/cert0.der" "$OUT/stock_gki_module_signing.der"
rmdir "$OUT/certs"
openssl x509 -inform DER -in "$OUT/stock_gki_module_signing.der" -out "$OUT/stock_gki_module_signing.pem"
openssl x509 -in "$OUT/stock_gki_module_signing.pem" -noout -subject -dates -ext subjectKeyIdentifier \
  | tee "$OUT/certs.txt"
grep -q 'Build time autogenerated kernel key' "$OUT/certs.txt"

rm "$OUT/Image"
