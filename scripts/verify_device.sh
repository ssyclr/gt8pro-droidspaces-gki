#!/usr/bin/env bash
# Check a phone booted into the Droidspaces kernel. Runs on the PC over adb.
#
# Usage: verify_device.sh [--stress] [stock_modules.txt]
#
#   --stress            also run processes inside new PID namespaces for a
#                       while. On a kernel without patch 007 this panics the
#                       phone (oplus_bsp_midas), so only use it on a build
#                       that has the patch.
#   stock_modules.txt   optional list of module names (one per line) loaded
#                       under the stock kernel, to diff against.
set -uo pipefail

STRESS=0
BASELINE=
for arg in "$@"; do
  case "$arg" in
    --stress) STRESS=1 ;;
    *) BASELINE=$arg ;;
  esac
done

export MSYS_NO_PATHCONV=1
su_sh() { adb shell "su -c '$1'" 2>&1 | tr -d '\r'; }

echo "== device"
adb get-state >/dev/null || { echo "no adb device" >&2; exit 1; }
adb shell getprop ro.product.model | tr -d '\r'
adb shell uname -r | tr -d '\r'

echo "== Droidspaces options in the running kernel"
su_sh 'zcat /proc/config.gz' | grep -E "^CONFIG_(SYSVIPC|POSIX_MQUEUE|IPC_NS|PID_NS|DEVTMPFS|USER_NS|MACVLAN|IP6_NF_NAT|IP_SET|NETFILTER_XT_SET|TMPFS_POSIX_ACL|TMPFS_XATTR|CFS_BANDWIDTH|MODVERSIONS)=|CGROUP_PIDS"

echo "== namespaces (expect ipc, pid, user among them)"
su_sh 'ls /proc/self/ns/' | tr '\n' ' '; echo

echo "== kernel keyring (expect 2 build keys: this kernel's and the stock one)"
su_sh 'grep "Build time autogenerated kernel key" /proc/keys'

echo "== module errors in dmesg (expect none)"
su_sh 'dmesg' | grep -iE "disagrees about version|Unknown symbol|module verification|exports protected|exports duplicate|Loading of .* is rejected" || echo "(none)"

echo "== loaded modules"
mods=$(su_sh 'cut -d" " -f1 /proc/modules' | sort)
echo "loaded: $(echo "$mods" | wc -l)"
if [ -n "$BASELINE" ]; then
  echo "missing vs baseline: $(comm -23 <(sort "$BASELINE") <(echo "$mods") | tr '\n' ' ')"
  echo "extra vs baseline:   $(comm -13 <(sort "$BASELINE") <(echo "$mods") | tr '\n' ' ')"
fi
su_sh 'grep -E "^(oplus_bsp_midas|rust_binder|rfkill|cfg80211|btpower|kernelsu) " /proc/modules'

echo "== namespace and filesystem probes (root)"
probe() {
  printf '%-48s ' "$1"
  su_sh "$1 >/dev/null 2>&1; echo \$?" | tail -1 | sed 's/^0$/ok/; s/^[1-9].*/FAIL (exit &)/'
}
probe "unshare -i true"
probe "unshare -U true"
probe "unshare -m -u -i -n true"
probe "mkdir -p /data/local/tmp/vd_dev && mount -t devtmpfs devtmpfs /data/local/tmp/vd_dev && umount /data/local/tmp/vd_dev && rmdir /data/local/tmp/vd_dev"
probe "mkdir -p /data/local/tmp/vd_mq && mount -t mqueue mqueue /data/local/tmp/vd_mq && umount /data/local/tmp/vd_mq && rmdir /data/local/tmp/vd_mq"

if [ "$STRESS" = 1 ]; then
  echo "== PID namespace stress"
  # Processes inside a new PID namespace get accounted on many scheduler
  # ticks, which is what made oplus_bsp_midas dereference NULL. The exec
  # loop also covers the execve hook of oplus_secure_guard_new.
  su_sh 'for i in $(seq 1 20); do unshare -p -f sh -c "sleep 0.3; true" || echo round $i failed; done; echo "20 short-lived namespaces: done"'
  su_sh 'unshare -p -f sh -c "i=0; while [ \$i -lt 100 ]; do /system/bin/toybox true; i=\$((i + 1)); done; echo \"execs inside one namespace: \$i\"; sleep 10" && echo "10 s in one namespace: done"'
  sleep 3
  if adb get-state >/dev/null 2>&1; then
    echo "still up, uptime: $(adb shell "cut -d' ' -f1 /proc/uptime" | tr -d '\r')s"
    su_sh 'dmesg' | grep -E "Unable to handle|Internal error|Kernel panic|BUG: " || echo "(no oops in dmesg)"
  else
    echo "device dropped off adb: it probably panicked; see /data/persist_log/backup/SYSTEM_LAST_KMSG.txt after reboot"
  fi
fi

echo "== misc"
su_sh 'echo tainted=$(cat /proc/sys/kernel/tainted); getenforce'
su_sh 'cmd wifi status' | head -1
